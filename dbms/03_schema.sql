-- Converted from the original SQLite schema.
-- Contains 9 tables, relationships, constraints and indexes.
-- =========================================================

-- Drop existing tables in dependency order
DROP TABLE IF EXISTS reviews CASCADE;
DROP TABLE IF EXISTS shop_products CASCADE;
DROP TABLE IF EXISTS shop_categories CASCADE;
DROP TABLE IF EXISTS shops CASCADE;
DROP TABLE IF EXISTS synonyms CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS markets CASCADE;
DROP TABLE IF EXISTS cities CASCADE;

-- 1. CITIES
CREATE TABLE cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    state TEXT NOT NULL,
    aliases TEXT
);

-- 2. MARKETS
CREATE TABLE markets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id INTEGER NOT NULL REFERENCES cities(id),
    name TEXT NOT NULL,
    area TEXT,
    description TEXT,
    market_type TEXT,
    numbering_notes TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION
);

-- 3. CATEGORIES
CREATE TABLE categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    name_hi TEXT,
    icon TEXT
);

-- 4. PRODUCTS
-- Product types, not individual inventory items.
CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES categories(id),
    name TEXT NOT NULL UNIQUE
);

-- 5. SYNONYMS
CREATE TABLE synonyms (
    term TEXT NOT NULL,
    category_id INTEGER NOT NULL REFERENCES categories(id),
    PRIMARY KEY (term, category_id)
);

-- 6. SHOPS
CREATE TABLE shops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id INTEGER NOT NULL REFERENCES markets(id),
    shop_number TEXT,
    block_area TEXT,
    location_hint TEXT,
    name TEXT,
    price_tier TEXT
        CHECK (price_tier IN ('budget', 'mid', 'premium')),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN (
            'active',
            'temporarily_closed',
            'permanently_closed',
            'moved',
            'hidden'
        )),
    verification_level TEXT NOT NULL DEFAULT 'unverified'
        CHECK (verification_level IN (
            'unverified',
            'community_confirmed',
            'admin_verified',
            'owner_verified'
        )),
    source TEXT NOT NULL DEFAULT 'admin',
    last_updated_at TEXT NOT NULL,
    last_verified_at TEXT,
    CHECK (
        shop_number IS NOT NULL
        OR name IS NOT NULL
        OR location_hint IS NOT NULL
    )
);

-- A shop number can repeat in different blocks,
-- but not within the same block of the same market.
CREATE UNIQUE INDEX uq_shop_number
ON shops (
    market_id,
    COALESCE(block_area, ''),
    shop_number
)
WHERE shop_number IS NOT NULL;

CREATE INDEX idx_shops_market
ON shops (market_id, status);

-- 7. SHOP_CATEGORIES
-- Many-to-many relationship between shops and categories.
CREATE TABLE shop_categories (
    shop_id INTEGER NOT NULL
        REFERENCES shops(id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL
        REFERENCES categories(id),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (shop_id, category_id)
);

-- 8. SHOP_PRODUCTS
-- Products sold by shops, including price range.
CREATE TABLE shop_products (
    shop_id INTEGER NOT NULL
        REFERENCES shops(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL
        REFERENCES products(id),
    price_min INTEGER,
    price_max INTEGER,
    last_confirmed_at TEXT NOT NULL,
    PRIMARY KEY (shop_id, product_id),
    CHECK (price_min <= price_max)
);

-- 9. REVIEWS
CREATE TABLE reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL
        REFERENCES shops(id) ON DELETE CASCADE,
    reviewer_name TEXT NOT NULL,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body TEXT,
    status TEXT NOT NULL DEFAULT 'published'
        CHECK (status IN ('pending', 'published', 'rejected', 'removed')),
    created_at TEXT NOT NULL
);

CREATE INDEX idx_reviews_shop
ON reviews (shop_id, status);

